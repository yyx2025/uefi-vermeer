#!/usr/bin/env python3
"""Emit the assembly that defines the VerifiedRoot symbols the kernel link needs.

Mirrors what scripts/build-verified-root-probe.py writes, but takes the manifest
and anchor this host produced instead of the ones a live device session made:

    _verified_root_manifest, _verified_root_manifest_bytes
    _verified_root_key                          (395 bytes)
    _verified_root_policies, _verified_root_policy_count
    _verified_root_sample_indices/lengths/samples

The policy table is what configureVerification() walks: one [manifest, size]
pair per signed volume. `_verified_root_policy_count` must equal the number of
pairs, or vr_open's caller sees a mismatch.

Usage:
  python emit_verified_root_asm.py --manifest FILE --key FILE --out FILE
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--manifest', required=True)
    parser.add_argument('--key', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--samples', help='a file of 4096-byte sample blocks (optional)')
    args = parser.parse_args()

    manifest = Path(args.manifest)
    key = Path(args.key)
    manifest_bytes = manifest.stat().st_size
    key_bytes = key.stat().st_size
    if key_bytes != 395:
        raise SystemExit(f'anchor is {key_bytes} bytes, VerifiedRoot expects 395')

    # The header records the image size at offset 24; the policy table publishes
    # it so the consumer can cross-check without parsing the envelope.
    image_bytes = struct.unpack_from('<Q', manifest.read_bytes()[:32], 24)[0]

    lines = [
        '// Generated by tools/vermeer-zh/emit_verified_root_asm.py',
        '// Offline packaging inputs for the VerifiedRoot seam; not a boot-root',
        '// authorization and not derived from an Apple signing key.',
        '.section __DATA_CONST,__const',
        '.balign 8',
        '.globl _verified_root_manifest, _verified_root_manifest_bytes',
        '_verified_root_manifest:',
        f'.incbin "{manifest}"',
        '_verified_root_manifest_bytes:',
        '.quad . - _verified_root_manifest',
        '',
        '.balign 8',
        '.globl _verified_root_key',
        '_verified_root_key:',
        f'.incbin "{key}"',
        '',
        '.balign 8',
        '.globl _verified_root_policies, _verified_root_policy_count',
        '_verified_root_policies:',
        # One [manifest pointer, size] pair. Both are quadwords, so the size has
        # to be its own operand -- writing "%d" next to the symbol truncated it.
        f'.quad _verified_root_manifest',
        f'.quad {manifest_bytes}',
        '_verified_root_policy_count:',
        '.quad 1',
    ]

    samples = Path(args.samples) if args.samples else None
    if samples and samples.is_file():
        count = samples.stat().st_size // 4096
        lines += [
            '',
            '.balign 8',
            '.globl _verified_root_sample_indices',
            '_verified_root_sample_indices:',
            '.quad ' + ','.join(str(i) for i in range(count)),
            '.globl _verified_root_sample_lengths',
            '_verified_root_sample_lengths:',
            '.quad ' + ','.join('4096' for _ in range(count)),
            '.globl _verified_root_samples',
            '_verified_root_samples:',
            f'.incbin "{samples}"',
        ]

    Path(args.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')

    print(f'manifest: {manifest} ({manifest_bytes:,} bytes)')
    print(f'  envelope image_bytes {image_bytes:,}')
    print(f'  manifest sha256 {hashlib.sha256(manifest.read_bytes()).hexdigest()[:16]}')
    print(f'key:      {key} ({key_bytes} bytes)')
    print(f'policies: 1 pair (manifest, {manifest_bytes})')
    print(f'wrote {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
