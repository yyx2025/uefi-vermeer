#!/usr/bin/env python3
"""Generate the CJK bitmap font header for vermeerPkg's boot menu.

Input : GNU Unifont .hex (GNU Unifont License v2, with the font embedding
        exception, so the glyphs may be compiled into firmware).
Output: a C header with
          * per-glyph bitmaps, 16x16 for CJK (2 bytes per row) and
            8x16 for printable ASCII, packed as bytes
          * a sorted codepoint -> index table for binary search
          * counts, so the renderer can assert its tables

Unifont .hex line format:
    4E2D:01000100010001003FF8210821082108...     -- 16x16, 4 hex chars/row
    0041:0000000018242442427E424242420000        -- 8x16,  2 hex chars/row
A glyph height is implied by the row count (16 here); the width is decided by
the hex digits per row (2 -> 8 px, 4 -> 16 px).

Usage:
  python gen-cjk-font.py --hex unifont.hex.gz --out VermeerCjkFont.h \
      --chars "维米尔引导菜单..."   [--extra-file chars.txt]

The glyph set is exactly the characters the boot UI shows, so the FV only
carries the few hundred CJK glyphs it needs instead of all 57k.
"""
import argparse
import gzip
import sys
from pathlib import Path

ASCENT = 16
CJK_WIDTH = 16
ASCII_WIDTH = 8


def load_hex(path):
    """codepoint -> (width_px, rows) where rows is a list of ints."""
    opener = gzip.open if str(path).endswith('.gz') else open
    glyphs = {}
    with opener(path, 'rt', encoding='utf-8', errors='replace') as stream:
        for line in stream:
            line = line.strip()
            if not line or ':' not in line:
                continue
            code, bitmap = line.split(':', 1)
            try:
                codepoint = int(code, 16)
            except ValueError:
                continue
            bitmap = bitmap.strip()
            hex_per_row = 2 if len(bitmap) % 64 == 0 and len(bitmap) <= 32 else 4
            # Decide by the height rule: ASCII is 8x16 (32 hex chars), CJK 16x16 (64).
            if len(bitmap) == 32:
                width, hex_per_row, height = 8, 2, 16
            elif len(bitmap) == 64:
                width, hex_per_row, height = 16, 4, 16
            elif len(bitmap) == 128:
                width, hex_per_row, height = 16, 4, 32
            else:
                # Skip unusual glyphs rather than guessing.
                continue
            rows = [int(bitmap[i * hex_per_row:(i + 1) * hex_per_row], 16) for i in range(height)]
            glyphs[codepoint] = {'width': width, 'height': height, 'rows': rows}
    return glyphs


def gather(chars, extra_file):
    wanted = {ord(c) for c in chars if c.strip()}
    if extra_file:
        for line in Path(extra_file).read_text(encoding='utf-8').splitlines():
            for c in line:
                if c.strip():
                    wanted.add(ord(c))
    return wanted


def emit_header(glyphs, wanted, *sources):
    missing = sorted(cp for cp in wanted if cp not in glyphs)
    present = sorted(cp for cp in wanted if cp in glyphs)

    lines = []
    lines.append('/** @file')
    lines.append('  CJK + ASCII bitmap font for the vermeer boot menu.')
    lines.append('')
    lines.append('  Generated by tools/gen-cjk-font.py from GNU Unifont 15.1.05')
    lines.append('  (GNU Unifont License v2, with the font embedding exception).')
    lines.append('  Do not edit by hand: regenerate when the UI strings change.')
    lines.append('')
    lines.append('  ASCII subset: printable 0x20..0x7E, 8x16.')
    lines.append('  CJK subset  : exactly the characters the menu prints, 16x16.')
    lines.append('')
    lines.append('  SPDX-License-Identifier: GPL-2.0-or-later WITH Font-exception-2.0')
    lines.append('**/')
    lines.append('')
    lines.append('#include "VermeerCjkFont.h"')
    lines.append('')
    lines.append(f'#define VERMEER_FONT_ASCII_FIRST  0x{0x20:04X}')
    lines.append(f'#define VERMEER_FONT_ASCII_LAST   0x{0x7E:04X}')
    lines.append(f'#define VERMEER_FONT_ASCII_COUNT  {0x7E - 0x20 + 1}')
    lines.append('')

    # ASCII: 8 wide, 16 tall -> 16 bytes per glyph, one byte per row.
    ascii_glyphs = [cp for cp in range(0x20, 0x7F) if cp in glyphs]
    lines.append(f'STATIC CONST UINT8  mAsciiGlyphs[{len(ascii_glyphs)}][{ASCENT}] = {{')
    for cp in ascii_glyphs:
        rows = glyphs[cp]['rows']
        body = ', '.join(f'0x{row & 0xFF:02X}' for row in rows[:ASCENT])
        lines.append(f'  {{ {body} }},  // 0x{cp:04X}')
    lines.append('};')
    lines.append('')

    # CJK: 16 wide, 16 tall -> 32 bytes per glyph, two bytes per row.
    cjk = [cp for cp in present if cp > 0x7E]
    lines.append(f'STATIC CONST UINT8  mCjkGlyphs[{len(cjk)}][{ASCENT * 2}] = {{')
    for cp in cjk:
        rows = glyphs[cp]['rows']
        body = ', '.join(f'0x{(row >> 8) & 0xFF:02X}, 0x{row & 0xFF:02X}' for row in rows[:ASCENT])
        lines.append(f'  {{ {body} }},  // U+{cp:04X}')
    lines.append('};')
    lines.append('')

    lines.append(f'STATIC CONST UINT32  mCjkCodepoints[{len(cjk)}] = {{')
    for start in range(0, len(cjk), 8):
        chunk = cjk[start:start + 8]
        lines.append('  ' + ', '.join(f'0x{cp:04X}' for cp in chunk) + ',')
    lines.append('};')
    lines.append('')

    lines.append(f'#define VERMEER_FONT_CJK_COUNT  {len(cjk)}')
    lines.append('')

    # Lookup: binary search over the sorted codepoint table.
    lines.append('CONST UINT8 *')
    lines.append('VermeerFontLookup (')
    lines.append('  IN  UINT32  Codepoint,')
    lines.append('  OUT UINTN   *Width,')
    lines.append('  OUT UINTN   *Stride')
    lines.append('  )')
    lines.append('{')
    lines.append('  UINTN  Low;')
    lines.append('  UINTN  High;')
    lines.append('  UINTN  Mid;')
    lines.append('')
    lines.append('  if ((Codepoint >= VERMEER_FONT_ASCII_FIRST) && (Codepoint <= VERMEER_FONT_ASCII_LAST)) {')
    lines.append('    *Width  = VERMEER_ASCII_WIDTH;')
    lines.append('    *Stride = 1;')
    lines.append('    return mAsciiGlyphs[Codepoint - VERMEER_FONT_ASCII_FIRST];')
    lines.append('  }')
    lines.append('')
    lines.append('  Low  = 0;')
    lines.append(f'  High = {len(cjk)};')
    lines.append('  while (Low < High) {')
    lines.append('    Mid = Low + (High - Low) / 2;')
    lines.append('    if (mCjkCodepoints[Mid] == Codepoint) {')
    lines.append('      *Width  = VERMEER_CJK_WIDTH;')
    lines.append('      *Stride = 2;')
    lines.append('      return mCjkGlyphs[Mid];')
    lines.append('    }')
    lines.append('')
    lines.append('    if (mCjkCodepoints[Mid] < Codepoint) {')
    lines.append('      Low = Mid + 1;')
    lines.append('    } else {')
    lines.append('      High = Mid;')
    lines.append('    }')
    lines.append('  }')
    lines.append('')
    lines.append('  return NULL;')
    lines.append('}')
    lines.append('')
    lines.append('BOOLEAN')
    lines.append('VermeerFontIsBmp (')
    lines.append('  IN UINT16  Unit')
    lines.append('  )')
    lines.append('{')
    lines.append('  // 0xD800..0xDFFF are the UTF-16 surrogate range; everything else is BMP.')
    lines.append('  return (BOOLEAN)((Unit < 0xD800) || (Unit > 0xDFFF));')
    lines.append('}')
    lines.append('')
    return '\n'.join(lines), missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hex', required=True, help='Unifont .hex or .hex.gz')
    parser.add_argument('--chars', default='', help='characters to include')
    parser.add_argument('--extra-file', help='file whose characters are also included')
    parser.add_argument('--out', required=True, help='output header path')
    args = parser.parse_args()

    glyphs = load_hex(args.hex)
    wanted = gather(args.chars, args.extra_file)
    header, missing = emit_header(glyphs, wanted, args.hex, args.chars)
    Path(args.out).write_text(header, encoding='utf-8')

    print(f'font: {len(glyphs)} glyphs in {args.hex}')
    print(f'wanted {len(wanted)} characters; wrote {args.out}')
    if missing:
        print(f'MISSING {len(missing)} glyphs: ' + ', '.join(f'U+{cp:04X}' for cp in missing))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
